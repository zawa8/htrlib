// Unified uL -> xi38 maps for all 10 scripts (Phase 1e-2b).
//
// Each script's map is a 128-entry (0x00-0x7F) array, one entry per
// codepoint offset within that script's Unicode block. Offsets are
// relative to the block start (hindi: 0x0900, bangla: 0x0980, ...,
// sinhala: 0x0D80).
//
// uL_to_xi38.ts computes li = (charCode >>> 7) and ki = charCode & 0x7F,
// looks up the script via SCRIPT_BY_LI[li], then UTEN128_MAP[script][ki].
//
// Phase 1e-2b: this file owns the data inline. The old per-script
// u1..u10_map.ts files still exist (untouched) and remain authoritative
// for hard_consonants_modulo_list / vovli_modulo_list until Phase 1f
// migrates those too.

